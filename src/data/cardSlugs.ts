// Harekeleri ve elif/ye/te-merbuta farklarını yok sayan anahtar
function strip(s: string): string {
  return s
    .replace(/[ؐ-ًؚ-ٰٟـ]/g, "")
    .replace(/[أإآٱ]/g, "ا").replace(/ى/g, "ي").replace(/ئ/g, "ي").replace(/ة/g, "ه")
    .trim();
}

// Harekesiz hâli birden fazla görsele denk gelen kelimeler (مَلِك / مُلْك / مَلَك gibi)
// belirsizdir; bunlar yalnızca tam (harekeli) eşleşmeyle bulunur.
const STRIPPED: Record<string, string | null> = {};
for (const [ar, slug] of Object.entries(CARD_SLUGS)) {
  const k = strip(ar);
  if (k in STRIPPED && STRIPPED[k] !== slug) STRIPPED[k] = null;
  else STRIPPED[k] = slug;
}

function lookupStripped(k: string): string | null {
  const v = STRIPPED[k];
  return v === undefined ? null : v;
}

export function getCardSlug(arabic: string): string | null {
  if (!arabic) return null;
  if (CARD_SLUGS[arabic]) return CARD_SLUGS[arabic];
  const k = strip(arabic);
  const direct = lookupStripped(k);
  if (direct) return direct;
  // Ayet içindeki kelimeler için: baştaki و / ف / ب / ل ve ال eklerini soy
  const prefixes = ["وال", "فال", "بال", "لل", "ال", "و", "ف", "ب"];
  for (const p of prefixes) {
    if (k.startsWith(p) && k.length - p.length >= 2) {
      const rest = k.slice(p.length);
      const hit = lookupStripped(rest) ?? lookupStripped("ال" + rest);
      if (hit) return hit;
    }
  }
  return null;
}

export function getCardImage(arabic: string): string | null {
  const slug = getCardSlug(arabic);
  return slug ? `/cards/${slug}.webp` : null;
}
